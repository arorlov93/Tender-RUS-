def qty(p):
    g, ng = p.get("qty_guaranteed") or 0, p.get("qty_non_guaranteed") or 0
    f = lambda v: f"{v:g}"
    return f(g + ng) + (f" (в т.ч. {f(g)} — март 2027, {f(ng)} — по заявкам)" if ng else "")


def spec(fn, title, nums):
    wb = Workbook(); ws = wb.active; ws.title = "Спецификация"
    ws.append([title]); ws.cell(1, 1).font = Font(bold=True, size=12)
    ws.append([NOTE]); ws.append([])
    ws.append(["№", "Наименование (ГОСТ / ТУ)", "Доп. требования", "Ед.", "Кол-во", "Цена за ед. с НДС, ₽", "Ставка НДС", "Производитель / страна",
               "Номер реестровой записи РПП (ПП 719)", "Срок поставки", "Упаковка / примечание"])
    for c in ws[4]: c.fill = H; c.font = HF; c.alignment = W
    for i, n in enumerate(nums, 1):
        p = P[n]; ws.append([i, clean(p["name"]), clean(p.get("extra")), p["unit"], qty(p)] + [""] * 6)
    for i, w in enumerate([5, 55, 40, 7, 26, 14, 10, 22, 22, 14, 24], 1): ws.column_dimensions[CL(i)].width = w
    for row in ws.iter_rows(min_row=5):
        for c in row: c.alignment = W
    wb.save(OUT + fn); return fn


