def para(d, text, bold=False, align=None, size=None):
    """текст с [плейсхолдерами] — плейсхолдеры жёлтым"""
    p = d.add_paragraph()
    for part in re.split(r"(\[[^\]]*\])", text):
        if not part: continue
        run = p.add_run(part); run.bold = bold
        if size: run.font.size = Pt(size)
        if part.startswith("["): run.font.highlight_color = WD_COLOR_INDEX.YELLOW
    if align == "c": p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if align == "r": p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    return p
