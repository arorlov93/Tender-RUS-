KEEP = re.compile(r"(?i)температур|диапазон|условное давление|сечение|рабочая среда|назначение|область")
RISK = re.compile(r"(?i)\d\s*–\s*\d|\d\s+-\s*\d|~|около|\bили\b|либо|не менее|не более|не ниже|\bдо\b|\bот\b|обычно|часто|например|зависит")

def chars(n):
    if n in FULL: return FULL[n]
    out = []
    for ln in [x.strip() for x in re.split(r"\n", TZ[n]["spec"]) if x.strip()]:
        if ":" not in ln:
            m = re.match(r"^(\D+?)\s+((?:от\s+)?\d.*)$", ln)
            if not m: out.append((ln, "", False)); continue  # подзаголовок («Габариты и вес»)
            ln = m.group(1) + ": " + m.group(2)
        k, v = [x.strip() for x in ln.split(":", 1)]
        ov = next((OV[key] for key in OV if key[0] == n and k.lower().startswith(key[1].lower())), None)
        if ov is not None: out.append((k, ov, True)); continue
        m = re.match(r"(?i)^(не более|не менее|не ниже|до)\s+(.*)$", v)
        if m and not KEEP.search(k): out.append((k, m.group(2), True)); continue
        out.append((k, v, bool(RISK.search(v)) and not KEEP.search(k)))
    return out

