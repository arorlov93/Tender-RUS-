def setp(p, text, bold=None, size=None):
    """Заменить текст абзаца, сохранив формат первого прогона; [..] — жёлтая заливка."""
    rpr = None
    if p.runs and p.runs[0]._r.rPr is not None: rpr = copy.deepcopy(p.runs[0]._r.rPr)
    for r in list(p.runs): r._r.getparent().remove(r._r)
    for part in PH.split(text):
        if not part: continue
        r = p.add_run(part)
        if rpr is not None: r._r.insert(0, copy.deepcopy(rpr))
        if part.startswith("[") and part.endswith("]"): r.font.highlight_color = WD_COLOR_INDEX.YELLOW
        if bold is not None: r.bold = bold
        if size: r.font.size = Pt(size)
    return p

def rep(p, pairs):
    t = p.text
    for a, b in pairs: t = t.replace(a, b)
    return setp(p, t)

def cset(cell, text, size=None, bold=None):
    ps = cell.paragraphs
    setp(ps[0], text, bold=bold, size=size)
    for p in ps[1:]: p._p.getparent().remove(p._p)

