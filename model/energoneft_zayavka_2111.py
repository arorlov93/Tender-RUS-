def words(n):
    u = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
    uf = ["", "одна", "две"] + u[3:]
    t = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
    d = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
    h = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"]
    forms = [("", "", ""), ("тысяча", "тысячи", "тысяч"), ("миллион", "миллиона", "миллионов")]
    def tri(x, fem):
        r = [h[x // 100]]; x %= 100
        if 10 <= x < 20: r.append(t[x - 10])
        else: r += [d[x // 10], (uf if fem else u)[x % 10]]
        return [w for w in r if w]
    def plural(x, f):
        x %= 100
        if 11 <= x <= 19: return f[2]
        return f[0] if x % 10 == 1 else f[1] if 2 <= x % 10 <= 4 else f[2]
    out, i = [], 0
    while n > 0:
        x = n % 1000
        if x: out = tri(x, i == 1) + ([plural(x, forms[i])] if i else []) + out
        n //= 1000; i += 1
    return " ".join(out) or "ноль"

def rub(v):
    r = int(round(v * 100)); R, K = divmod(r, 100)
    s = f"{R:,}".replace(",", " ") + f",{K:02d}"
    w = words(R); w = w[0].upper() + w[1:]
    e = R % 100
    rw = "рублей" if 11 <= e <= 19 else "рубль" if R % 10 == 1 else "рубля" if 2 <= R % 10 <= 4 else "рублей"
    return f"{s} ({w}) {rw} {K:02d} коп."

