def conv(v):
    """значение ТЗ → конкретное значение для первой части"""
    s = re.sub(r"\s+", " ", v).strip()
    m = re.fullmatch(r"(?i)не менее ?(-?\s?\d+)\s*не более ?(\+?\s?\d+)", s.replace(" ", " "))
    if m: return f"от {m.group(1).replace(' ', '')} до {m.group(2).replace(' ', '')}", True
    m = re.fullmatch(r"(?i)от ?(-?\d+) ?до ?(\+?\d+)", s.replace(" ", ""))
    if m: return f"от {m.group(1)} до {m.group(2)}", False
    m = re.fullmatch(r"(?i)не более ?\+? ?(\d+)", s)
    if m:
        n = int(m.group(1)); return (f"+{425 if n == 450 else n}" if n >= 100 else str(n)), True
    m = re.fullmatch(r"(?i)не менее ?(\d+)", s)
    if m: return m.group(1), True
    return s, False

