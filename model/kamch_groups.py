"""Камчатка: группировка 315 позиций по типу/марке арматуры — для запроса КП у заводов."""
import json, re
RULES = [
    ("Краны трёхходовые/манометровые (11б18бк, 11б27п 3-ход.)", r"11б18|3-?х ходов|трехход|манометр"),
    ("Краны шаровые латунные (11б27п1, 11б27п, LD Pride)", r"кран.*11б27|кран.*латун|pride"),
    ("Краны шаровые нержавеющие (10нж45фт, КШХ, нерж.)", r"кран.*(10нж|нерж|кшх|12х18)"),
    ("Краны шаровые стальные (11с67п, 11с22п, LD КШ, КЗШС, ЦУФ)", r"кран|кшц|кшрф|кзшс"),
    ("Задвижки чугунные (30ч6бр, 30ч906бр, 30ч39р)", r"задвижк.*30ч"),
    ("Задвижки нержавеющие (30нж41нж, 30нж947нж)", r"задвижк.*30нж"),
    ("Задвижки стальные (30с41нж, 30с64нж, 30с964нж, 30с941нж, 30с576нж)", r"задвижк"),
    ("Затворы дисковые (межфланцевые, ПА954, Stensel, ЗПВС)", r"затвор"),
    ("Клапаны предохранительные (17лс17нж, 17с28нж, ПСК, СППК)", r"предохран|17[лс]|пск|сппк"),
    ("Клапаны обратные (16ч42р, 19с76нж, 19нж76нж, 16нж10нж)", r"обратн|16ч|19с|19нж|19ч|16нж"),
    ("Клапаны регулирующие и регуляторы (25ч945п, Ридан VFG/NVD, РД-НО, АРТ)", r"регулир|регулятор|ридан|vfg|nvd|рд-но|арт-|25ч|25с"),
    ("Клапаны запорные / вентили (15с22нж, 15нж65нж, 15кч, 15ч, 14нж)", r"клапан|вентил|15[сч]|15нж|15кч|14нж|15б"),
    ("Электроприводы и редукторы (ГЗ, Тулаэлектропривод, Н-В, ЭП)", r"привод|редуктор|н-в-02|шкаф управлен"),
    ("Фланцы и крепёж", r"фланц|крепеж|шпильк"),
    ("Запчасти, уплотнения, рыбозащита, прочее", r"."),
]
def group(name):
    s = name.lower()
    for g, rx in RULES:
        if re.search(rx, s): return g
if __name__ == "__main__":
    Q = json.load(open("data/kamch/kam_qty.json"))
    P = {}
    for g in "ABC":
        for x in json.load(open(f"data/kamch/price_{g}.json")):
            P[(re.search(r"1\.\d", x["spec"]).group(0), x["n"])] = x
    out = {}
    for q in Q:
        p = P.get((q["table"], q["n"]), {})
        g = group(q["name"])
        d = out.setdefault(g, dict(positions=[], value=0.0))
        d["positions"].append(dict(table=q["table"], n=q["n"], name=q["name"], qty=q["qty"], price=p.get("price"), supplier=p.get("supplier")))
        d["value"] += (p.get("price") or 0) * q["qty"]
    json.dump(out, open("data/kamch/groups.json", "w"), ensure_ascii=False, indent=1)
    for g, d in sorted(out.items(), key=lambda kv: -kv[1]["value"]):
        print(f'{d["value"]/1e6:6.2f} млн  {len(d["positions"]):3d} поз  {g}')
