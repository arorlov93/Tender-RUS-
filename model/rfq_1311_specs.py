def b2b(num):
    out = []
    for fn in [f"{S}/work/rows_{num}.txt", f"{S}/txt/b2bpos_{num}.txt"]:
        try: lines = open(fn).read().splitlines()
        except FileNotFoundError: continue
        for l in lines:
            m = pat.match(l)
            if m: out.append(dict(name=m[1].strip(), qty=float(m[2].replace(" ", "").replace(",", ".")), unit=m[3], req=""))
        if out: break
    seen = set(); res = []
    for o in out:
        k = (o["name"], o["qty"])
        if k not in seen: seen.add(k); res.append(o)
    return res
