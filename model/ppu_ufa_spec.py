"""Спецификация для запроса КП у заводов: отводы ППУ-ПЭ для МУП «Уфимские инженерные сети» (договор по 32616450774).
Требования — дословно из ТЗ (Прил. 1 к извещению, data/ppu_ufa/tz_verbatim.json); завод подтверждает каждую строку. Наших цен нет."""
import json, re, openpyxl
from openpyxl.styles import Font, PatternFill, Border, Side
from tidy import tidy

TZ = json.load(open("data/ppu_ufa/tz_verbatim.json"))
thin = Side(style="thin", color="BFBFBF"); FILL = PatternFill("solid", fgColor="FFF2CC"); BOX = Border(top=thin, bottom=thin, left=thin, right=thin)
M = '#,##0" ₽"'


def head(ws):
    for c in ws[ws.max_row]:
        if c.value is not None: c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor="305496")


def find(p, rx):
    t = " ".join(p["lines"]); m = re.search(rx, t)
    return m.group(1).strip() if m else "в ТЗ не указано"


wb = openpyxl.Workbook(); ws = wb.active; ws.title = "Спецификация"
ws.append(["Запрос коммерческого предложения: отводы ППУ-ПЭ, поставка в г. Уфа (МУП «Уфимские инженерные сети»)"]); ws["A1"].font = Font(bold=True, size=13)
ws.append(["Товар должен полностью соответствовать ТЗ заказчика — оно приведено дословно на листе «ТЗ дословно». Просим подтвердить каждую строку. Жёлтые поля заполняет завод."])
H = ["№", "Наименование (как в ТЗ)", "Кол-во, шт", "Стенка, мм (ТЗ)", "Присоединение к трубе (ТЗ)", "Марка стали (ТЗ)", "Рабочие параметры (ТЗ)", "Неизолированные концы, мм (ТЗ)",
     "Проводники ОДК (ТЗ)", "Овальность торцов (ТЗ)", "Тип изоляции по обозначению", "Диаметр оболочки ПЭ, мм — указывает завод", "Длина плеч L×L, мм — указывает завод",
     "Цена за шт с НДС, склад завода, ₽", "Сумма, склад завода, ₽", "Цена за шт с НДС с доставкой до Уфы, ₽", "Сумма до Уфы, ₽", "Срок изготовления, раб. дн.", "Наличие", "Вес 1 шт, кг"]
ws.append(H); head(ws)
for p in TZ:
    X = ws.max_row + 1; t = " ".join(p["lines"])
    odk = re.search(r"устанавливаться (\S+) проводника", t)
    ws.append([p["n"], p["name"].split("#")[0].strip(), int(p["qty"]), find(p, r"толщина стенки мм ([\d,]+)"), find(p, r"Для присоединения к трубе ([^.]+?)(?: толщина|$)"),
               find(p, r"(?:Марка стали|марка стали) (не хуже ст\.20|[^.]+)"), find(p, r"с параметрами: (рабочим давлением[^.]+?°С)"), find(p, r"неизолированных концов изделий должна быть ([\d\s\-]+)"),
               f'{odk.group(1)}, медь ММ 1,5 мм²: положение {find(p, r"в положении (.+?ч)\. при")}, шов {find(p, r"сварного шва стальной трубы ([\d±]+ч)")}' if odk else "в ТЗ не указано", find(p, r"(Овальность торцов труб и патрубков[^.]+)"),
               "тип 1 («-1-» в обозначении)", None, None, None, f"=C{X}*N{X}", None, f"=C{X}*P{X}"])
    for j in (12, 13, 14, 16, 18, 19, 20): ws.cell(X, j).fill = FILL
    for j in (14, 15, 16, 17): ws.cell(X, j).number_format = M
X = ws.max_row + 1
ws.append(["", "ИТОГО", f"=SUM(C4:C{X - 1})"] + [""] * 11 + [f"=SUM(O4:O{X - 1})", "", f"=SUM(Q4:Q{X - 1})"])
for j in (15, 17): ws.cell(X, j).number_format = M
for c in ws[X]: c.font = Font(bold=True)
for row in ws.iter_rows(min_row=3):
    for c in row: c.border = BOX
for i, w in enumerate([4, 26, 7, 8, 18, 18, 20, 12, 22, 22, 12, 14, 14, 14, 14, 14, 14, 11, 10, 9], 1): ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
ws.append([])
for t in ["Диаметр оболочки и длина плеч в ТЗ не заданы: укажите ваши для типа изоляции 1 по ГОСТ 30732-2020 и подтвердите, что изделие с ними соответствует обозначению из ТЗ.",
          "Условия оплаты: предоплата 50% после подписания договора, остаток — после поставки (подтвердите или предложите свои). Срок: товар нужен в течение 7 дней с момента заявки заказчика.",
          "К КП приложите: письмо о полном соответствии ТЗ (лист «ТЗ дословно» с отметками), образцы паспорта и сертификатов из листа «Документы к отгрузке».",
          "Изготовитель, город завода, контактное лицо, телефон, e-mail: ______________________________"]:
    ws.append([t]); ws.merge_cells(start_row=ws.max_row, start_column=1, end_row=ws.max_row, end_column=20)

tz = wb.create_sheet("ТЗ дословно")
tz.append(["Поз.", "Наименование", "Требование ТЗ (дословно)", "Соответствует? (да / нет)", "Фактическое значение / чем подтверждается"]); head(tz)
for p in TZ:
    for k, line in enumerate(p["lines"]):
        tz.append([p["n"] if k == 0 else "", p["name"].split("#")[0].strip() if k == 0 else "", line, None, None])
        for j in (4, 5): tz.cell(tz.max_row, j).fill = FILL
        for c in tz[tz.max_row]: c.border = BOX
for i, w in enumerate([5, 22, 110, 14, 36], 1): tz.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
tz.freeze_panes = "C2"

DOCS = [("Паспорт на изделие (партию) с датой изготовления — не ранее 2025 г.", "все", "ТЗ поз. 3, 4: документ о дате изготовления; маркировка — дата изготовления"),
        ("Документ завода об исправности системы ОДК на дату отгрузки", "все (в ТЗ — поз. 3, 4)", "ТЗ поз. 3, 4"),
        ("Сертификат соответствия ТР ТС 032/2013", "все", "ТЗ все позиции"),
        ("Сертификат соответствия ФНИП (оборудование под избыточным давлением)", "все", "ТЗ все позиции"),
        ("Сертификат ГОСТ 15150-69", "все", "ТЗ все позиции"),
        ("Сертификат ГОСТ 30732-2020", "все", "ТЗ все позиции"),
        ("Сертификат ГОСТ 16338-85 (полиэтилен)", "все", "ТЗ все позиции"),
        ("Сертификаты ГОСТ 17375-2001 и ГОСТ 17380-2001 (отводы)", "все", "ТЗ все позиции"),
        ("Сертификаты ГОСТ 10704-91 и ГОСТ 10705-80 (труба)", "поз. 1 (108)", "ТЗ поз. 1"),
        ("Сертификат ГОСТ 20295-85 (труба)", "поз. 2, 3, 4", "ТЗ поз. 2–4"),
        ("Сертификаты качества на все материалы (сталь, ППУ, ПЭ)", "все", "ТЗ все позиции"),
        ("Маркировка на оболочке (или бирке): обозначение, завод, № партии, дата изготовления; не ближе 200 мм от торца изоляции", "все", "ТЗ все позиции"),
        ("Заглушки и гидроизоляционное покрытие торцов изоляции", "все (в ТЗ — поз. 2, 3, 4)", "ТЗ поз. 2–4"),
        ("Гарантийный талон: гарантия не менее 12 мес. и не менее гарантии завода; срок службы не менее 10 лет", "все", "договор п. 14.1; ТЗ поз. 3, 4"),
        ("Счёт-фактура, товарная накладная или УПД, отгрузочные документы", "все", "договор п. 3.3, 5.3")]
dc = wb.create_sheet("Документы к отгрузке")
dc.append(["№", "Документ / требование", "Для каких позиций", "Основание", "Завод предоставит? (да / нет)"]); head(dc)
for i, (a, b, c) in enumerate(DOCS, 1):
    dc.append([i, a, b, c, None]); dc.cell(dc.max_row, 5).fill = FILL
    for x in dc[dc.max_row]: x.border = BOX
for i, w in enumerate([4, 80, 22, 26, 16], 1): dc.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
tidy(wb, row_h=40)
for r in range(2, tz.max_row + 1):
    v = str(tz.cell(r, 3).value or ""); tz.row_dimensions[r].height = max(18, 15 * (len(v) // 120 + 1) + 4)
wb.save("../PPU_UFA_SPEC_KP.xlsx")
print("ok", sum(len(p["lines"]) for p in TZ), "строк ТЗ")
