"""Спецификации для запроса КП у заводов (без цен заказчика): РусГидро — Нерюнгринская ГРЭС-2 (багерная насосная) и АО «Теплосеть СПб».
→ ../SPEC_RUSGIDRO_NERYUNGRI.xlsx, ../SPEC_TEPLOSET_SPB.xlsx"""
import json
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
N = json.load(open("data/zakupki_2011_valves/neryungri/analysis.json"))
S = json.load(open("data/zakupki_2011_valves/spb/analysis.json"))
H = PatternFill("solid", fgColor="0B2545"); HF = Font(bold=True, color="FFFFFF"); Y = PatternFill("solid", fgColor="FFF2CC")
T = Side(style="thin", color="999999"); BR = Border(left=T, right=T, top=T, bottom=T)
FILL = ["Производитель (завод)", "Марка / тип изделия", "Страна", "№ реестровой записи РПП (ПП 719)", "Цена за ед., ₽ с НДС", "Срок изготовления, нед.", "Масса, кг", "Примечание / отклонения от ТЗ"]

def head(ws, title, lines):
    ws.append([title]); ws["A1"].font = Font(bold=True, size=13)
    for l in lines: ws.append([l])
    ws.append([])

def table(ws, hdr, rows, widths, fill_from):
    r0 = ws.max_row + 1; ws.append(hdr)
    for c in ws[r0]: c.fill = H; c.font = HF; c.alignment = Alignment(wrap_text=True, vertical="center"); c.border = BR
    for r in rows:
        ws.append(r)
        for i, c in enumerate(ws[ws.max_row], 1):
            c.alignment = Alignment(wrap_text=True, vertical="top"); c.border = BR
            if i >= fill_from: c.fill = Y
    for i, w in enumerate(widths, 1): ws.column_dimensions[ws.cell(1, i).column_letter].width = w
    ws.freeze_panes = ws.cell(r0 + 1, 3)

